const CATALOGS: Record<AppLang, Record<string, string>> = { zh: ZH, en: EN };

let currentLang: AppLang = 'zh';

export function normalizeLang(lang: string | undefined | null): AppLang {
    if (lang && lang.toLowerCase().startsWith('en')) {
        return 'en';
    }
    return 'zh';
}

export function setAppLang(lang: string | undefined | null): AppLang {
    currentLang = normalizeLang(lang);
    return currentLang;
}

export function getAppLang(): AppLang {
    return currentLang;
}

export function catalogKeys(lang: AppLang): string[] {
    return Object.keys(CATALOGS[lang]);
}

export function t(key: string, ...args: Array<string | number>): string {
    let catalog: Record<string, string> = CATALOGS[currentLang] ?? ZH;
    let template: string = catalog[key] ?? CATALOGS.en[key] ?? key;
    for (let i = 0; i < args.length; i++) {
        template = template.replace(new RegExp('\\{' + i + '\\}', 'g'), String(args[i]));
    }
    return template;
}

export function tt(html: string, tooltipKey: string): string {
    return html + '<span class="tooltiptext bottomTooltip">' + t(tooltipKey) + '</span>';
}
